stonecutter {
    create(rootProject) {
        /** One node per loader, named `{minecraft}-{loader}`, each built by `build.{loader}.gradle.kts`. */
        fun match(version: String, vararg loaders: String) {
            for (loader in loaders) version("$version-$loader", version).buildscript("build.$loader.gradle.kts")
        }

        match("1.21.1", "fabric", "neoforge")
        match("1.21.4", "fabric", "neoforge")
        match("1.21.5", "fabric", "neoforge")
        match("1.21.8", "fabric", "neoforge")
        match("1.21.10", "fabric", "neoforge")
        match("1.21.11", "fabric", "neoforge")
        match("26.1.2", "fabric", "neoforge")
        match("26.2", "fabric", "neoforge")
        match("26.3", "fabric", "neoforge")
        // The state the source is committed in (`./gradlew "Reset active project"` before committing).
        vcsVersion = "1.21.1-neoforge"
    }
}

